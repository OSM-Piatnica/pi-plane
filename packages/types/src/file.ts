import type { EFileAssetType } from "./enums";

export type TFileMetaDataLite = {
  name: string;
  // file size in bytes
  size: number;
  type: string;
};

export type TFileEntityInfo = {
  entity_identifier: string;
  entity_type: EFileAssetType;
};

export type TFileMetaData = TFileMetaDataLite & TFileEntityInfo;

export type TFileSignedURLResponse = {
  asset_id: string;
  asset_url: string;
  upload_data: {
    url: string;
    /** The form fields of an S3-compatible presigned POST; empty for a PUT upload. */
    fields: Record<string, string>;
    /** POST (a multipart form, the default) for S3-compatible storage, PUT (the file as the body) for Azure Blob Storage. */
    method?: "POST" | "PUT";
    /** Headers the upload request must carry; only sent for a PUT. */
    headers?: Record<string, string>;
  };
};

export type TDuplicateAssetData = {
  entity_id: string;
  entity_type: EFileAssetType;
  project_id?: string;
  asset_ids: string[];
};

export type TDuplicateAssetResponse = Record<string, string>; // asset_id -> new_asset_id
