import { observer } from "mobx-react";
// plane imports
import { EUserPermissions, EUserPermissionsLevel } from "@plane/constants";
import { useTranslation } from "@plane/i18n";
// components
import { NotAuthorizedView } from "@/components/auth-screens/not-authorized-view";
import { PageHead } from "@/components/core/page-title";
import { SettingsContentWrapper } from "@/components/settings/content-wrapper";
import { DocumentLibrariesSettings } from "@/components/workspace/document-libraries/document-libraries-settings";
// hooks
import { useWorkspace } from "@/hooks/store/use-workspace";
import { useUserPermissions } from "@/hooks/store/user";
// local imports
import type { Route } from "./+types/page";
import { DocumentLibrariesWorkspaceSettingsHeader } from "./header";

const WorkspaceDocumentLibrariesSettingsPage = observer(function WorkspaceDocumentLibrariesSettingsPage({
  params,
}: Route.ComponentProps) {
  // router
  const { workspaceSlug } = params;
  // translation
  const { t } = useTranslation();
  // store hooks
  const { workspaceUserInfo, allowPermissions } = useUserPermissions();
  const { currentWorkspace } = useWorkspace();
  // derived values
  const isAdmin = allowPermissions([EUserPermissions.ADMIN], EUserPermissionsLevel.WORKSPACE);
  const pageTitle = currentWorkspace?.name
    ? `${currentWorkspace.name} - ${t("workspace_settings.settings.document_libraries.title")}`
    : undefined;

  if (workspaceUserInfo && !isAdmin) {
    return <NotAuthorizedView section="settings" className="h-auto" />;
  }

  return (
    <SettingsContentWrapper header={<DocumentLibrariesWorkspaceSettingsHeader />}>
      <PageHead title={pageTitle} />
      <DocumentLibrariesSettings workspaceSlug={workspaceSlug} />
    </SettingsContentWrapper>
  );
});

export default WorkspaceDocumentLibrariesSettingsPage;
